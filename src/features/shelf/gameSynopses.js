/**
 * Busca sinopse e screenshots conhecidos para um título
 */
export function getGameSynopsisAndMedia(title = '') {
  if (!title) return null
  const clean = title.toLowerCase().trim()

  for (const [key, data] of Object.entries(RETRO_GAME_SYNOPSES)) {
    if (clean === key || clean.includes(key) || key.includes(clean)) {
      return data
    }
  }

  return {
    synopsis: 'Um clássico reverenciado da era retrô dos videogames. Supere desafios pixelizados, domine os comandos e marque seu nome no pódio de quem zerou este grande título.',
    genre: 'Retrô Clássico',
    releaseYear: 'Clássico',
    screenshots: [],
  }
}

